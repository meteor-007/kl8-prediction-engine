def get_road_012(num: int) -> int:
    """获取号码的 012 路归属（模 3 同余）。

    @param num 号码 (1..80)
    @return 0, 1, 或 2
    @raises ValueError 号码越界
    """
    if not (1 <= num <= N_NUM):
        raise ValueError(f"号码 {num} 非法，必须在 1..{N_NUM} 范围内")
    return num % 3


def is_prime(num: int) -> bool:
    """判定号码是否为质数。

    @param num 号码 (1..80)
    @return True 为质数，False 为非质数
    """
    return num in PRIMES_80


def get_zone4(num: int) -> int:
    """获取号码所属四分区索引 (0..3)。

    @param num 号码 (1..80)
    @return 0=一区, 1=二区, 2=三区, 3=四区
    """
    if not (1 <= num <= N_NUM):
        raise ValueError(f"号码 {num} 非法，必须在 1..{N_NUM} 范围内")
    return (num - 1) // 20
